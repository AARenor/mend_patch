type Tree = Record<string, string>;
type Changes = Record<string, string | null>;

interface TestCase {
  name: string;
  family: string;
  argv: string[];
  stdin: string | null;
  files: Tree;
  expect: {
    exit: number;
    stdout: string;
    after?: Changes;
  };
}

/** `a\nb\n`; no arguments is the empty file. */
const lines = (...xs: string[]): string => (xs.length === 0 ? '' : `${xs.join('\n')}\n`);
/** `a\nb`; no final line break. */
const bare = (...xs: string[]): string => xs.join('\n');
/** CRLF line breaks, with a final CRLF. */
const crlf = (...xs: string[]): string => `${xs.join('\r\n')}\r\n`;
/** One JSON edit object per line (JSON Lines), trailing line break. */
const jsonLines = (...edits: Record<string, unknown>[]): string => `${edits.map((e) => JSON.stringify(e)).join('\n')}\n`;
/** A pretty-printed JSON array of edit objects, trailing line break. */
const jsonArray = (...edits: Record<string, unknown>[]): string => `${JSON.stringify(edits, null, 2)}\n`;

