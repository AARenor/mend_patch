function writeTree(dir: string, files: Tree): void {
  for (const [path, text] of Object.entries(files)) {
    const abs = join(dir, ...path.split('/'));
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, text);
  }
}

function readTree(dir: string): Tree {
  const out: Tree = {};
  const walk = (d: string): void => {
    for (const name of readdirSync(d)) {
      const abs = join(d, name);
      const st = statSync(abs);
      if (st.isDirectory()) walk(abs);
      else if (st.isFile()) out[relative(dir, abs).split(sep).join('/')] = readFileSync(abs, 'utf8');
    }
  };
  walk(dir);
  return out;
}

function wantedTree(c: TestCase): Tree {
  const out: Tree = { ...c.files };
  for (const [path, text] of Object.entries(c.expect.after ?? {})) {
    if (text === null) delete out[path];
    else out[path] = text;
  }
  return out;
}

function runCase(c: TestCase): string[] {
  const dir = mkdtempSync(join(tmpdir(), 'mend-test-'));
  try {
    writeTree(dir, c.files);
    const env: Record<string, string | undefined> = { ...process.env };
    delete env.MAKEFUN_ENV_URL;
    const r = spawnSync(process.execPath, [MAIN, ...c.argv], {
      cwd: dir,
      env,
      input: c.stdin ?? '',
      encoding: 'utf8',
      timeout: TIMEOUT_MS,
      maxBuffer: 8 * 1024 * 1024,
    });
    const problems: string[] = [];
    if (r.error !== undefined) problems.push(`spawn failed: ${r.error.message}`);
    const exit = r.status === null ? 124 : r.status;
    if (exit !== c.expect.exit) problems.push(`exit ${exit}, expected ${c.expect.exit}${r.signal === null ? '' : ` (signal ${r.signal})`}`);
    const stdout = r.stdout ?? '';
    if (stdout !== c.expect.stdout) problems.push(`stdout ${JSON.stringify(stdout)}, expected ${JSON.stringify(c.expect.stdout)}`);
    const want = wantedTree(c);
    const got = readTree(dir);
    for (const path of [...new Set([...Object.keys(want), ...Object.keys(got)])].sort()) {
      if (!(path in want)) problems.push(`unexpected file ${JSON.stringify(path)}: ${JSON.stringify(got[path])}`);
      else if (!(path in got)) problems.push(`missing file ${JSON.stringify(path)}, expected ${JSON.stringify(want[path])}`);
      else if (got[path] !== want[path]) problems.push(`file ${JSON.stringify(path)} is ${JSON.stringify(got[path])}, expected ${JSON.stringify(want[path])}`);
    }
    return problems;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const seen = new Set<string>();
for (const c of cases) {
  if (seen.has(c.name)) throw new Error(`duplicate case name: ${c.name}`);
  seen.add(c.name);
}

const filters = process.argv.slice(2);
const picked = filters.length === 0 ? cases : cases.filter((c) => filters.some((f) => c.family === f || c.name.startsWith(f) || c.name.includes(f)));
let failed = 0;
for (const c of picked) {
  const problems = runCase(c);
  if (problems.length === 0) continue;
  failed += 1;
  process.stdout.write(`FAIL ${c.name}\n`);
  for (const problem of problems) process.stdout.write(`  ${problem}\n`);
}
process.stdout.write(`${picked.length - failed} of ${picked.length} passed\n`);
if (failed > 0) process.exitCode = 1;
