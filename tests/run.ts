// An independent test runner for mend (SPEC.md), not the kit's runner.ts.
//
// Each case gets a fresh temporary directory holding exactly its `files`, then runs
// `node main.ts <argv>` with its stdin, and compares the exit code, stdout and every
// regular file afterwards.  `expect.after` is a delta on `files`: a string replaces the
// bytes, null deletes the path, and a path that is absent from both is not allowed to
// appear.  Standard error is ignored, as SPEC.md says.
//
//   node tests/run.ts                 all cases
//   node tests/run.ts unified json    cases whose family or name matches a word
//
// The check families follow SPEC.md's sections: usage, patch, format, json, unified,
// search, v4a, crlf, newline, output, atomic and move.  Names such as `unified/...`
// or `json/...` show the sentence under test.

